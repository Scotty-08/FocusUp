        .init(id: "axolotl", name: "Axolotl", artboard: "Axolotl", unlock: .level(60)),
    ]

    static func species(_ id: String) -> CompanionSpecies {
        all.first { $0.id == id } ?? all[0]
    }

    /// Skin tones / hair colors, in the rig's input order (kit.py SKINS/HAIRS).
    static let skinTones: [(name: String, color: Color)] = [
        ("Porcelain", Color(hex: 0xF4D9C6)), ("Light", Color(hex: 0xE9BC98)), ("Medium", Color(hex: 0xC98E68)),
        ("Tan", Color(hex: 0xA96E47)), ("Brown", Color(hex: 0x7E4F31)), ("Deep", Color(hex: 0x55341F)),
    ]
    static let hairColors: [(name: String, color: Color)] = [
        ("Black", Color(hex: 0x1E1B1E)), ("Dark Brown", Color(hex: 0x3B2619)), ("Brown", Color(hex: 0x6B4226)),
        ("Auburn", Color(hex: 0x8E3B22)), ("Blonde", Color(hex: 0xD9B25E)), ("Silver", Color(hex: 0xC9CCD3)),
    ]

    /// Static portrait for small spots (friends list, companion picker),
    /// in the cloak the player wears. Humans also have one per skin tone.
    /// Generated by avatar-companions/tools/icons.py.
    static func portraitName(for config: AvatarConfig) -> String {
        portraitName(species: species(config.species), skin: config.skin, cloakItemID: config.cloak)
    }

    static func portraitName(species: CompanionSpecies, skin: Int = 2, cloakItemID: String = "cloak.forest") -> String {
        let cloak = cloakKey(for: cloakItemID)
        if species.isHuman {
            let tone = min(max(skin, 0), skinTones.count - 1)
            return "portrait_\(species.id.replacingOccurrences(of: ".", with: "_"))_\(tone)_\(cloak)"
        }
        return "portrait_\(species.id)_\(cloak)"
    }

    /// Rig cloak index -> the name used in portrait assets (kit.py CLOAKS order).
    private static let cloakKeys = ["forest", "storm", "ember", "celestial", "cyan", "slate"]

    private static func cloakKey(for itemID: String) -> String {
        let index = AvatarCatalog.item(itemID)?.rigIndex ?? 0
        return cloakKeys.indices.contains(index) ? cloakKeys[index] : "forest"
    }
}

extension Color {
    init(hex: UInt32) {
        self.init(red: Double((hex >> 16) & 0xFF) / 255,
                  green: Double((hex >> 8) & 0xFF) / 255,
                  blue: Double(hex & 0xFF) / 255)
    }
}
