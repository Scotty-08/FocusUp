import SwiftUI

/// A companion the player can be: the two human starters plus the
/// unlockable animals. `artboard` names the artboard in Companions/
/// companions.riv (built from avatar-companions/, see tools/companions.py).
struct CompanionSpecies: Identifiable, Hashable {
    enum Unlock: Hashable {
        /// Everyone has it.
        case starter
        /// Free once the player reaches this level.
        case level(Int)
        /// Bought with coins -- priced well above any cosmetic.
        case coins(Int)
    }

    let id: String
    let name: String
    let artboard: String
    let unlock: Unlock

    var isHuman: Bool { id.hasPrefix("human.") }

    /// Owned-items key for coin unlocks (shares CharacterStore.ownedItems).
    var ownedKey: String { "companion.\(id)" }
}

enum CompanionCatalog {
    static let defaultSpeciesID = "human.male"

    /// Starters first, then unlocks roughly in the order a player reaches
    /// them. Level unlocks are spaced 5-10 levels apart (a level is 200
    /// EXP, about two medium quests), so the Axolotl at level 60 takes
    /// ~120 quests; coin unlocks sit far above any cosmetic (max 300).
    /// Thresholds and prices live only here -- tune them freely.
    static let all: [CompanionSpecies] = [
