/// A player's look: which companion, the item id per slot, and (for the
/// human starters) skin tone and hair color indices.
struct AvatarConfig: Codable, Equatable {
    var robe: String
    var eyes: String
    var cloak: String
    var headwear: String
    var species: String
    var boots: String
    var augment: String
    var skin: Int
    var hair: Int

    init(robe: String = "robe.midnight", eyes: String, cloak: String, headwear: String = "headwear.none",
         species: String = CompanionCatalog.defaultSpeciesID, boots: String = "boots.brown",
         augment: String = "augment.none", skin: Int = 2, hair: Int = 1) {
        self.robe = robe
        self.eyes = eyes
        self.cloak = cloak
        self.headwear = headwear
        self.species = species
        self.boots = boots
        self.augment = augment
        self.skin = skin
        self.hair = hair
    }

    static let starter = AvatarConfig(eyes: "eyes.cyan", cloak: "cloak.cyan")

    private enum CodingKeys: String, CodingKey {
        case robe, eyes, cloak, headwear, species, boots, augment, skin, hair
    }

    /// Configs saved before companions existed (and friends' profiles from
    /// older builds) only have robe/eyes/cloak/headwear; everything newer
    /// falls back to the starter human in brown boots.
    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        let s = AvatarConfig.starter
        robe = try c.decodeIfPresent(String.self, forKey: .robe) ?? s.robe
        eyes = try c.decodeIfPresent(String.self, forKey: .eyes) ?? s.eyes
        cloak = try c.decodeIfPresent(String.self, forKey: .cloak) ?? s.cloak
        headwear = try c.decodeIfPresent(String.self, forKey: .headwear) ?? s.headwear
        species = try c.decodeIfPresent(String.self, forKey: .species) ?? s.species
        boots = try c.decodeIfPresent(String.self, forKey: .boots) ?? s.boots
        augment = try c.decodeIfPresent(String.self, forKey: .augment) ?? s.augment
        skin = try c.decodeIfPresent(Int.self, forKey: .skin) ?? s.skin
        hair = try c.decodeIfPresent(Int.self, forKey: .hair) ?? s.hair
    }

    func itemID(for slot: AvatarSlot) -> String {
        switch slot {
        case .robe: return robe
        case .eyes: return eyes
        case .cloak: return cloak
        case .headwear: return headwear
        case .boots: return boots
        case .augment: return augment
        }
    }

    func setting(_ itemID: String, for slot: AvatarSlot) -> AvatarConfig {
        var copy = self
        switch slot {
        case .robe: copy.robe = itemID
        case .eyes: copy.eyes = itemID
        case .cloak: copy.cloak = itemID
        case .headwear: copy.headwear = itemID
        case .boots: copy.boots = itemID
        case .augment: copy.augment = itemID
        }
        return copy
    }

    func withSpecies(_ id: String) -> AvatarConfig {
        var copy = self
        copy.species = id
        return copy
    }
}
