import SwiftUI

/// Everything about the player's companion that can be customized.
///
/// `eyes`, `cloak`, `boots` and `augment` are what the animated companion
/// actually wears (see CompanionAvatarView) and what the shop sells.
/// `robe` and `headwear` belong to the old pixel avatar: they're kept so
/// saved configs, owned items and friends on older builds still decode,
/// but they are no longer shown or sold.
enum AvatarSlot: String, CaseIterable, Codable {
    case robe, eyes, cloak, headwear, boots, augment

    /// The slots the companion wears, in shop-tab order.
    static let companionSlots: [AvatarSlot] = [.eyes, .cloak, .boots, .augment]

    var label: String {
        switch self {
        case .robe: return "Robe"
        case .eyes: return "Eyes"
        case .cloak: return "Cloak"
        case .headwear: return "Headwear"
        case .boots: return "Boots"
        case .augment: return "Extras"
        }
    }
}

/// Which headwear shape the legacy PixelAvatarView draws.
enum Headwear: String {
    case none, horns, crown, halo
}

/// One customization option. `cost == 0` means it's free for everyone;
/// anything above 0 is bought with coins (see CharacterStore.buy).
///
/// `rigIndex` is the value the companion rig's state machine input takes
/// for this item -- the order of the EYES / CLOAKS / BOOTS / AUGMENTS
/// tables in avatar-companions/tools/kit.py. `iconName` is its shop icon
/// in Assets.xcassets/Companions (generated by tools/icons.py).
struct AvatarItem: Identifiable, Hashable {
    let id: String
    let slot: AvatarSlot
    let name: String
    let cost: Int
    /// RGB hex for color slots; used by the legacy pixel avatar.
    let hex: UInt32?
    let headwear: Headwear?
    var rigIndex: Int? = nil
    var iconName: String? = nil

    var color: Color? {
        guard let hex else { return nil }
        return Color(
            red: Double((hex >> 16) & 0xFF) / 255,
            green: Double((hex >> 8) & 0xFF) / 255,
            blue: Double(hex & 0xFF) / 255
        )
    }
}

enum AvatarCatalog {
    private static func legacy(_ slot: AvatarSlot, _ key: String, _ name: String, _ cost: Int, _ hex: UInt32) -> AvatarItem {
        AvatarItem(id: "\(slot.rawValue).\(key)", slot: slot, name: name, cost: cost, hex: hex, headwear: nil)
    }

    private static func headwear(_ key: String, _ name: String, _ cost: Int, _ shape: Headwear) -> AvatarItem {
        AvatarItem(id: "headwear.\(key)", slot: .headwear, name: name, cost: cost, hex: nil, headwear: shape)
    }

